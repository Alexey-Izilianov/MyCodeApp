/* Отступы табуляцией: колонки, клики и стрелки — по табстопам */
#include <stdio.h>

int main(void)
{
	int values[3] = {1, 2, 3};	/* комментарий после таба */
	for (int i = 0; i < 3; ++i) {
		if (values[i] % 2)
			printf("%d\n", values[i]);
	}
    return 0; /* эта строка — пробелами, должна стоять ровно под табом */
}
